parse_kepler_formulas <- function(f_vec) {
  n <- length(f_vec)
  c_v <- numeric(n); wM <- numeric(n); wT <- numeric(n)
  eval_frac <- function(s) {
    s <- gsub("[()]", "", s)
    if (grepl("/", s, fixed = TRUE)) {
      p <- as.numeric(strsplit(s, "/", fixed = TRUE)[[1]])
      return(p[1] / p[2])
    }
    as.numeric(s)
  }
  for (i in seq_len(n)) {
    f <- gsub(" ", "", f_vec[i])
    m_mat <- regmatches(f, regexpr("M_star\\^([0-9./()-]+)", f))
    wM[i] <- if (length(m_mat) == 1L) eval_frac(sub("M_star\\^", "", m_mat)) else 1/3
    t_mat <- regmatches(f, regexpr("T\\^([0-9./()-]+)", f))
    wT[i] <- if (length(t_mat) == 1L) eval_frac(sub("T\\^", "", t_mat)) else 2/3
    p_mat <- regmatches(f, regexpr("^[0-9.]+(?=\\*M_star)", f, perl = TRUE))
    c_v[i] <- if (length(p_mat) == 1L) as.numeric(p_mat) else 1.0
  }
  list(c = c_v, wM = wM, wT = wT)
}

