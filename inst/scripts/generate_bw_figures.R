# Exact Clopper-Pearson 95% CI helper (proportions in [0, 1])
cp_ci <- function(k, n, conf.level = 0.95) {
  alpha <- 1.0 - conf.level
  lo <- ifelse(k <= 0, 0.0, qbeta(alpha / 2.0, k, n - k + 1.0))
  hi <- ifelse(k >= n, 1.0, qbeta(1.0 - alpha / 2.0, k + 1.0, n - k))
  cbind(lo = lo, hi = hi)
}

# Dual Cairo PDF + 300-DPI PNG writer with full Unicode plotmath support
save_dual <- function(filename_base, width, height, plot_fn) {
  pdf_path <- file.path(out_dir, paste0(filename_base, ".pdf"))
  png_path <- file.path(out_dir, paste0(filename_base, ".png"))

  cairo_pdf(pdf_path, width = width, height = height, family = "sans")
  plot_fn()
  dev.off()

  png(png_path, width = width * 300, height = height * 300, res = 300, type = "cairo", family = "sans")
  plot_fn()
  dev.off()

  cat(sprintf("Generated %s (.pdf & .png)\n", filename_base))
}

# Clean background horizontal/vertical gridlines (drawn BEFORE data)
draw_grid_h <- function(ys) abline(h = ys, col = "#E6E8EB", lty = 1, lwd = 0.7)
draw_grid_v <- function(xs) abline(v = xs, col = "#E6E8EB", lty = 1, lwd = 0.7)

# Vertical error whiskers with optional white backing halo
draw_whiskers <- function(x, lo, hi, lwd = 1.7, length = 0.038, col = COL_CHAR, halo = FALSE) {
  valid <- is.finite(x) & is.finite(lo) & is.finite(hi)
  if (!any(valid)) return(invisible(NULL))
  xv <- x[valid]; lov <- lo[valid]; hiv <- hi[valid]
  diff_ok <- (hiv - lov) > 1e-12
  if (any(diff_ok)) {
    if (halo) {
      arrows(xv[diff_ok], lov[diff_ok], xv[diff_ok], hiv[diff_ok],
             angle = 90, code = 3, length = length, lwd = 3.2, col = "#FFFFFF")
    }
    arrows(xv[diff_ok], lov[diff_ok], xv[diff_ok], hiv[diff_ok],
           angle = 90, code = 3, length = length, lwd = lwd, col = col)
  }
}

# White-padded text helper so background gridlines / dotted ticks never cut through text
draw_padded_text <- function(x, y, labels, cex = 0.85, font = 1, col = "#000000",
                             pad_x = 0.02, pad_y = 0.02, border = NA, ...) {
  sw <- max(strwidth(labels, cex = cex, font = font))
  sh <- max(strheight(labels, cex = cex, font = font))
  rect(x - 0.5 * sw - pad_x, y - 0.5 * sh - pad_y,
       x + 0.5 * sw + pad_x, y + 0.5 * sh + pad_y,
       col = "#FFFFFF", border = border)
  text(x, y, labels = labels, cex = cex, font = font, col = col, ...)
}

