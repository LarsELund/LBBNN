extract_mat_ci <- function(ci_df, methods, metrics) {
  m_est <- matrix(NA_real_, nrow = length(metrics), ncol = length(methods), dimnames = list(metrics, methods))
  m_lo  <- m_est; m_hi <- m_est
  for (i in seq_along(metrics)) {
    for (j in seq_along(methods)) {
      r <- ci_df[ci_df$metric == metrics[i] & ci_df$method == methods[j], , drop = FALSE]
      if (nrow(r) == 1L) {
        m_est[i, j] <- r$mean
        m_lo[i, j]  <- r$ci_lo
        m_hi[i, j]  <- r$ci_hi
      }
    }
  }
  list(est = m_est, lo = m_lo, hi = m_hi)
}

get_sig_stars <- function(gl_df, methods, metric_name) {
  vapply(methods, function(m) {
    if (m == "Symbolic-LBBNN") return("")
    row <- gl_df[gl_df$metric == metric_name & gl_df$term == m, , drop = FALSE]
    if (nrow(row) != 1L || is.na(row$sig_star)) return("")
    row$sig_star[1]
  }, character(1))
}

draw_angled_x_labels <- function(x_centers, labels, y_offset_frac = 0.045, cex = 0.78) {
  usr <- par("usr")
  y_pos <- usr[3] - y_offset_frac * (usr[4] - usr[3])
  for (j in seq_along(x_centers)) {
    fnt <- ifelse(labels[j] == "Symbolic-LBBNN", 2, 1)
    text(x_centers[j], y_pos, labels = labels[j], srt = 35, adj = 1, xpd = TRUE,
         cex = cex, font = fnt, col = COL_BLACK)
  }
}

draw_grouped_ci_points <- function(mat_ci, methods, scale_mult = 100, ylim = c(-4, 134),
                                   ylab = "Percentage (%)", main_title = "",
                                   legend_labels = NULL, legend_pos = "topright",
                                   horiz_leg = FALSE, cex_names = 0.78,
                                   sig_stars = NULL, star_row = NULL) {
  est <- mat_ci$est * scale_mult
  lo  <- mat_ci$lo  * scale_mult
  hi  <- mat_ci$hi  * scale_mult
  n_r <- nrow(est)
  n_c <- ncol(est)

  x_centers <- seq_len(n_c)
  offs <- if (n_r == 2L) c(-0.16, 0.16) else c(-0.22, 0.0, 0.22)
  pchs <- if (n_r == 2L) c(16, 17) else c(16, 17, 15)
  cols <- if (n_r == 2L) c(COL_BLACK, "#666666") else c(COL_BLACK, "#555555", "#888888")
  ltys <- if (n_r == 2L) c(1, 2) else c(1, 2, 1)

  plot(NA, xlim = c(0.4, n_c + 0.6), ylim = ylim, xaxt = "n",
       xlab = "", ylab = ylab, main = main_title, las = 1)
  draw_grid_h(seq(0, 100, by = 20))
  draw_grid_v(x_centers)

  for (r in seq_len(n_r)) {
    xr <- x_centers + offs[r]
    for (c_idx in seq_len(n_c)) {
      if (is.finite(lo[r, c_idx]) && is.finite(hi[r, c_idx]) && (hi[r, c_idx] - lo[r, c_idx] > 1e-6)) {
        arrows(xr[c_idx], lo[r, c_idx], xr[c_idx], hi[r, c_idx],
               angle = 90, code = 3, length = 0.026, lwd = 1.7, lty = ltys[r], col = cols[r])
      }
      points(xr[c_idx], est[r, c_idx], pch = pchs[r], cex = 1.25, col = cols[r], bg = COL_WHITE, lwd = 1.5)
    }
  }

  # Add GLMM Wald significance stars directly above primary metric marker
  if (!is.null(sig_stars) && !is.null(star_row)) {
    xr_s <- x_centers + offs[star_row]
    for (c_idx in seq_len(n_c)) {
      st <- sig_stars[c_idx]
      if (nzchar(st)) {
        y_top_m <- max(est[star_row, c_idx], hi[star_row, c_idx], na.rm = TRUE)
        text(xr_s[c_idx], y_top_m + 5.2, labels = st, cex = 0.78, font = 2, col = COL_BLACK)
      }
    }
  }

  draw_angled_x_labels(x_centers, methods, y_offset_frac = 0.045, cex = cex_names)

  if (!is.null(legend_labels)) {
    legend(legend_pos, legend = legend_labels, pch = pchs, col = cols, lty = ltys, lwd = 1.7,
           pt.bg = COL_WHITE, horiz = horiz_leg, bty = "o", bg = COL_WHITE, box.col = COL_LIGHT, cex = 0.72)
  }
  invisible(x_centers)
}

